const langNameToCode: Record<string, string> = {
  english: "en",
  hindi: "hi",
  sanskrit: "sa",
  devanagari: "sa",
  kannada: "kn",
  telugu: "te",
  tamil: "ta",
  german: "de",
  french: "fr",
  spanish: "es",
  chinese: "zh",
  arabic: "ar",
  portuguese: "pt",
};

const langFallbacks: Record<string, string[]> = {
  hi: ["sa"],
  sa: ["hi"],
  de: ["en"],
  fr: ["en"],
  es: ["en"],
  zh: ["en"],
  ar: ["en"],
  pt: ["en"],
};

export function translateContent(
  text: string | null | undefined,
  map: ContentMap,
  lang: string
): string {
  if (!text) return "";
  const normalizedLang = langNameToCode[lang.toLowerCase()] || lang;
  const entry = map[text];
  if (entry) {
    if (entry[normalizedLang]) return entry[normalizedLang];
    const fallbacks = langFallbacks[normalizedLang];
    if (fallbacks) {
      for (const fb of fallbacks) {
        if (entry[fb]) return entry[fb];
      }
    }
  }
  return text;
}
