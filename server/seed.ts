export async function seedDatabase() {
  console.log("Checking if database needs seeding...");

  const existingBooks = await db.select().from(books);
  if (existingBooks.length > 0) {
    console.log("Database already seeded, skipping...");
    return;
  }

  console.log("Seeding database with Isha Upanishad Bhashya from advaitasharada.sringeri.net...");

  const book = await storage.createBook({
    slug: "isha-upanishad-bhashya",
    title: ISHA_UPANISHAD_BHASHYA.titleEnglish,
    author: ISHA_UPANISHAD_BHASHYA.authorEnglish,
    description: `${ISHA_UPANISHAD_BHASHYA.title} - ${ISHA_UPANISHAD_BHASHYA.author}

The Isha Upanishad (ईशावास्योपनिषद्) is one of the shortest and most celebrated Upanishads. This text presents Shankaracharya's Bhashya (commentary) on the 18 mantras, providing deep philosophical insights into Advaita Vedanta.

${ISHA_UPANISHAD_BHASHYA.introduction}`,
    category: "Upanishad Bhashya",
    coverImage: null,
    totalVerses: ISHA_UPANISHAD_BHASHYA.mantras.length,
  });

  console.log("Created book:", book.title);

  for (const mantra of ISHA_UPANISHAD_BHASHYA.mantras) {
    const verse = await storage.createVerse({
      bookId: book.id,
      verseNumber: mantra.number,
      sectionTitle: mantra.number === 1 ? "मन्त्र १" : `मन्त्र ${mantra.number}`,
    });

    await storage.createTranslation({
      verseId: verse.id,
      languageCode: "devanagari",
      content: mantra.mula,
    });

    await storage.createExplanation({
      verseId: verse.id,
      authorName: "Adi Shankaracharya",
      authorTitle: "आदि शङ्कराचार्य",
      languageCode: "devanagari",
      content: mantra.bhashya,
    });
  }

  console.log("Created mantras with Shankaracharya's Bhashya");
  console.log("Database seeding complete!");
}
