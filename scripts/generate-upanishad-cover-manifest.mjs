#!/usr/bin/env node
/** Writes client/src/lib/upanishad-cover-manifest.ts from public/images/upanishads/*.png */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "client/public/images/upanishads");
const out = path.join(root, "client/src/lib/upanishad-cover-manifest.ts");

const stems = fs
  .readdirSync(dir)
  .filter((f) => /\.png$/i.test(f))
  .filter((f) => !/brahma\s*sutra/i.test(f))
  .map((f) => f.replace(/\.png$/i, ""))
  .sort();

const body = `/** Auto-generated by npm run generate:upanishad-covers — do not edit by hand. */
export const UPANISHAD_COVER_STEMS = new Set<string>([
${stems.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
]);
`;

fs.writeFileSync(out, body);
console.log(`Wrote ${stems.length} cover stem(s) to ${path.relative(root, out)}`);
